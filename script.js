/* abs*/
console.log(Math.abs(-6));
console.log(Math.abs(6.9));

/*floor */
console.log(Math.floor(5.4));
console.log(Math.floor(-5.4));

/*  Math.ceil() */
console.log(Math.ceil(5.99));   // Output: 6
console.log(Math.ceil(-2.7));   // Output: -2 (rounds up towards zero)


/* Math.trunc() */


console.log(Math.trunc(42.84));   // Output: 42
console.log(Math.trunc(-7.9));    // Output: -7
console.log(Math.trunc(0.123));   // Output: 0
console.log(Math.trunc(-0.123));  // Output: -0
console.log(Math.trunc("5.5"));   // Output: 5
console.log(Math.trunc("abc"));   // Output: NaN


/**Math.pow() */

console.log(Math.pow(4,4));   // Output: 42
console.log(Math.pow(2,8));   // Output: 42
console.log(Math.pow(-2,4));   // Output: 42


/* Math.sign() */
console.log(Math.sign(-2));   // Output: 42
console.log(Math.sign(2));   // Output: 42


